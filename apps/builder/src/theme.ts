/**
 * Infima primary-color shades from a single `#rrggbb` color. The factors follow the palette
 * Docusaurus documents for its default green (`#2e8555`).
 */

const SHADES: Array<[string, number]> = [
  ["", 1],
  ["-dark", 0.9],
  ["-darker", 0.82],
  ["-darkest", 0.7],
  ["-light", 1.1],
  ["-lighter", 1.15],
  ["-lightest", 1.3],
];

function parseHex(hex: string): [number, number, number] {
  const m = /^#([0-9a-fA-F]{2})([0-9a-fA-F]{2})([0-9a-fA-F]{2})$/.exec(hex);
  if (!m) throw new Error(`Invalid hex color ${JSON.stringify(hex)}`);
  return [
    Number.parseInt(m[1] as string, 16),
    Number.parseInt(m[2] as string, 16),
    Number.parseInt(m[3] as string, 16),
  ];
}

function toHex(rgb: [number, number, number]): string {
  return `#${rgb
    .map((c) =>
      Math.max(0, Math.min(255, Math.round(c)))
        .toString(16)
        .padStart(2, "0"),
    )
    .join("")}`;
}

/** Mixes toward white by `amount` (0..1). */
function lighten(rgb: [number, number, number], amount: number): [number, number, number] {
  return rgb.map((c) => c + (255 - c) * amount) as [number, number, number];
}

function shades(rgb: [number, number, number]): Array<[string, string]> {
  return SHADES.map(([suffix, factor]) => [
    suffix,
    toHex(rgb.map((c) => c * factor) as [number, number, number]),
  ]);
}

/** CSS for `src/css/theme.generated.css`: light-mode shades on `:root`, brighter ones for dark mode. */
export function generateThemeCss(primaryColor: string): string {
  const base = parseHex(primaryColor);
  const light = shades(base);
  // Dark mode needs a lighter base to keep contrast against the dark surface.
  const dark = shades(lighten(base, 0.25));
  const block = (list: Array<[string, string]>) =>
    list.map(([suffix, value]) => `  --ifm-color-primary${suffix}: ${value};`).join("\n");
  return [
    "/* Generated by apps/builder from docs.yaml theme.primaryColor. Do not edit. */",
    ":root {",
    block(light),
    "  --docusaurus-highlighted-code-line-bg: rgba(0, 0, 0, 0.1);",
    "}",
    "",
    "[data-theme='dark'] {",
    block(dark),
    "  --docusaurus-highlighted-code-line-bg: rgba(0, 0, 0, 0.3);",
    "}",
    "",
  ].join("\n");
}
