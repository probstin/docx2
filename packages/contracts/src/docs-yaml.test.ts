import { describe, expect, it } from "vitest";
import { DocsYamlSchema } from "./docs-yaml.js";

const minimal = { schemaVersion: 1, site: { title: "Platform Engineering" } };

describe("DocsYamlSchema", () => {
  it("applies defaults to a minimal file", () => {
    const parsed = DocsYamlSchema.parse(minimal);
    expect(parsed.site.basePath).toBe("/");
    expect(parsed.navigation.mode).toBe("autogenerated");
    expect(parsed.content).toEqual({ root: "docs", landingPage: "index.md", exclude: [] });
    expect(parsed.theme).toEqual({ mode: "system", primaryColor: "#2563eb" });
    expect(parsed.assistant.enabled).toBe(true);
    expect(parsed.assistant.title).toBe("Ask AI");
  });

  it("accepts the illustrative v1 file from the plan", () => {
    const result = DocsYamlSchema.safeParse({
      schemaVersion: 1,
      site: {
        title: "Platform Engineering",
        tagline: "Internal docs",
        basePath: "/",
        logo: "assets/logo.svg",
      },
      navigation: { mode: "autogenerated" },
      content: { root: "docs", landingPage: "index.md", exclude: ["**/_drafts/**"] },
      theme: { mode: "system", primaryColor: "#2563eb" },
      assistant: {
        enabled: true,
        title: "Ask Engineering AI",
        welcomeMessage: "How can I help?",
        pageContext: true,
        citations: true,
        expandable: true,
      },
    });
    expect(result.success).toBe(true);
  });

  it.each([
    ["unknown top-level key", { ...minimal, plugins: ["evil"] }],
    ["unknown nested key", { ...minimal, assistant: { endpoint: "https://x" } }],
    ["unsupported schema version", { ...minimal, schemaVersion: 2 }],
    ["missing title", { schemaVersion: 1, site: {} }],
    ["path traversal in logo", { ...minimal, site: { title: "t", logo: "../secrets.txt" } }],
    ["absolute content root", { ...minimal, content: { root: "/etc" } }],
    ["windows drive path", { ...minimal, content: { root: "C:\\docs" } }],
    ["basePath without trailing slash", { ...minimal, site: { title: "t", basePath: "/docs" } }],
    ["bad color", { ...minimal, theme: { primaryColor: "blue" } }],
    ["unknown navigation mode", { ...minimal, navigation: { mode: "manual" } }],
  ])("rejects %s", (_name, input) => {
    expect(DocsYamlSchema.safeParse(input).success).toBe(false);
  });
});
