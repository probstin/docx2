import { z } from "zod";
import { RepoRelativePathSchema } from "./paths.js";

/**
 * `docs.yaml` v1 — the only configuration a documentation team owns.
 *
 * Every object is strict: unknown keys fail validation so teams cannot reach privileged
 * settings (endpoints, secrets, plugins) through this file. Parsing YAML text into an
 * object is the source adapter's job; this schema validates the result.
 */
export const DocsYamlSchema = z.strictObject({
  schemaVersion: z.literal(1),
  site: z.strictObject({
    title: z.string().trim().min(1).max(120),
    tagline: z.string().trim().max(240).optional(),
    /** URL path the site is served under. Must start and end with `/`. */
    basePath: z
      .string()
      .regex(/^\/(?:[A-Za-z0-9._-]+\/)*$/, "must start and end with '/' and contain only URL-safe segments")
      .default("/"),
    logo: RepoRelativePathSchema.optional(),
  }),
  navigation: z
    .strictObject({
      mode: z.literal("autogenerated").default("autogenerated"),
    })
    .prefault({}),
  content: z
    .strictObject({
      root: RepoRelativePathSchema.default("docs"),
      /** Relative to `content.root`. */
      landingPage: RepoRelativePathSchema.default("index.md"),
      /** Globs relative to `content.root`. */
      exclude: z.array(z.string().min(1).max(256)).max(50).default([]),
    })
    .prefault({}),
  theme: z
    .strictObject({
      mode: z.enum(["light", "dark", "system"]).default("system"),
      primaryColor: z
        .string()
        .regex(/^#[0-9a-fA-F]{6}$/, "must be a 6-digit hex color like #2563eb")
        .default("#2563eb"),
    })
    .prefault({}),
  assistant: z
    .strictObject({
      enabled: z.boolean().default(true),
      title: z.string().trim().min(1).max(80).default("Ask AI"),
      welcomeMessage: z.string().trim().min(1).max(500).default("How can I help?"),
      pageContext: z.boolean().default(true),
      citations: z.boolean().default(true),
      expandable: z.boolean().default(true),
    })
    .prefault({}),
});

export type DocsYaml = z.infer<typeof DocsYamlSchema>;
export type DocsYamlInput = z.input<typeof DocsYamlSchema>;

export const DOCS_YAML_FILENAME = "docs.yaml";
